"""Writes src/input/isotope_table.cpp, the nuclear isotopes CCEX knows without a gyrofile, from the EasySpin isotope database
(example/tools/SpinTensorReader/spHamilReader/spin_database/isotopedata.txt; magnetic moments from N. Stone, IAEA
INDC(NDS)-0658, 2014). Every isotope (mass number > 0) with a positive spin, named mass number + symbol ("13C"), with its spin and its
gyromagnetic ratio in the CCEX unit, gamma = gn muN / hbar (rad/ms/G), muN / hbar from CODATA 2018.
    python3 example/tools/IsotopeTable/make_isotope_table.py        (from the repository root)"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SRC = ROOT / "example/tools/SpinTensorReader/spHamilReader/spin_database/isotopedata.txt"
OUT = ROOT / "src/input/isotope_table.cpp"
MU_N = 5.0507837461e-27          # J/T, CODATA 2018
HBAR = 1.054571817e-34           # J s, exact
GAMMA_PER_GN = MU_N / HBAR * 1e-3 * 1e-4      # rad/s/T -> rad/ms/G

rows = []
for line in SRC.read_text(encoding="latin-1").splitlines():
    f = line.split()
    if not f or f[0].startswith("%"):
        continue
    protons, nucleons, radio, symbol, name, spin, gn = f[:7]
    # an isotope with a nuclear spin: a mass number, and a positive integer or half-integer spin (the database also
    # holds element rows with mass number 0 and spin -1, which are not isotopes; review 20261008-003400 R1)
    if int(nucleons) <= 0 or float(spin) <= 0:
        continue
    assert float(spin) * 2 == int(float(spin) * 2), (symbol, nucleons, spin)
    assert int(nucleons) >= int(protons) and float(gn) != 0, (symbol, nucleons, gn)
    rows.append((f"{nucleons}{symbol}", float(spin), float(gn) * GAMMA_PER_GN, radio == "*"))
names = [r[0] for r in rows]
assert len(names) == len(set(names)), "two isotopes with the same name"

body = "\n".join(f'    {{"{n}", {s:.1f}f, {g:.9g}}},{"  // radioactive" if rad else ""}' for n, s, g, rad in rows)
OUT.write_text(f'''// Generated by example/tools/IsotopeTable/make_isotope_table.py - do not edit by hand.
// Nuclear isotopes (mass number > 0) with a positive spin from the EasySpin isotope database (isotopedata.txt; magnetic moments from
// N. Stone, IAEA INDC(NDS)-0658, 2014): name (mass number + symbol), spin, gyromagnetic ratio gamma = gn muN / hbar in
// rad/ms/G (muN / hbar = {GAMMA_PER_GN:.9g} rad/ms/G per unit gn, CODATA 2018). Used for a bath species the gyrofile does
// not name, or for every species when there is no gyrofile.

#include "../../include/input/isotope_table.h"

#include <cstring>

static const IsotopeEntry kIsotopes[] = {{
{body}
}};

const IsotopeEntry* findIsotope(const char* name){{
    for (const IsotopeEntry& e : kIsotopes){{
        if (std::strcmp(e.name, name) == 0){{ return &e; }}
    }}
    return nullptr;
}}

int isotopeTableSize(){{ return (int)(sizeof(kIsotopes) / sizeof(kIsotopes[0])); }}
''')
print(f"{len(rows)} isotopes -> {OUT.relative_to(ROOT)}")
